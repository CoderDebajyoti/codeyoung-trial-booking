/**
 * Deduplicate any list of courses by stable course.id.
 * Preserves first encounter order and guarantees idempotent rendering.
 */
export function deduplicateCourses<T extends { id: string }>(courses: T[]): T[] {
  if (!Array.isArray(courses)) return [];
  const map = new Map<string, T>();
  courses.forEach((c) => {
    if (c && typeof c.id === 'string' && c.id.trim().length > 0 && !map.has(c.id)) {
      map.set(c.id, c);
    }
  });
  return Array.from(map.values());
}
